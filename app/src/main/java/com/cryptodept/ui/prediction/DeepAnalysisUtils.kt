package com.cryptodept.ui.prediction

import com.cryptodept.domain.model.Direction
import com.cryptodept.domain.model.PricePrediction
import java.util.Locale

fun generateShareText(prediction: PricePrediction): String {
    val resolver = com.cryptodept.util.SymbolResolver()
    val assetName = resolver.toDisplayName(prediction.coinId)
    val direction = prediction.ensembleConsensus.direction.name
    val confidence = (prediction.ensembleConsensus.overallConfidence * 100).toInt()

    return """
        --- CRYPTODEPT AI REPORT ---
        ASSET: $assetName
        SENTIMENT: $direction ($confidence%)
        
        PRICE DISTRIBUTION:
        - QUANT_TARGET: $${String.format(Locale.US, "%,.2f", prediction.priceDistribution.percentile90)}
        - MEDIAN_PRICE: $${String.format(Locale.US, "%,.2f", prediction.priceDistribution.percentile50)}
        - FLOOR_ZONE: $${String.format(Locale.US, "%,.2f", prediction.priceDistribution.percentile10)}
        
        PREDICTABILITY: ${(prediction.dataQuality * 100).toInt()}%
        ============================
        Generated by CryptoDept Terminal v3
        """.trimIndent()
}

fun generateAiPrompt(prediction: PricePrediction): String {
    val resolver = com.cryptodept.util.SymbolResolver()
    val asset = resolver.toDisplayName(prediction.coinId)
    val sentiment = prediction.ensembleConsensus.direction

    val symbolDesc =
        when (asset) {
            "BTC" -> "the classic orange Bitcoin 'B' logo"
            "ETH" -> "the blue Ethereum crystal diamond symbol"
            "XRP" -> "the modern white XRP 'X' logo"
            "SOL" -> "the Solana S-shaped logo with gradient colors"
            "ADA" -> "the Cardano circular dot constellation logo"
            "DOGE" -> "the Dogecoin golden 'D' logo"
            "DOT" -> "the Polkadot pink dot circle logo"
            "MATIC" -> "the Polygon purple geometric logo"
            else -> "the futuristic digital logo for $asset"
        }

    val dateStr = java.text.SimpleDateFormat("MMMM dd, yyyy", java.util.Locale.US).format(java.util.Date())
    val low = prediction.priceDistribution.percentile10
    val high = prediction.priceDistribution.percentile90

    val mood =
        when (sentiment) {
            Direction.STRONG_UP -> "aggressive bullish energy, golden light"
            Direction.UP -> "positive growth, green neon skyscraper reflections"
            Direction.DOWN -> "bearish storm, red lightning"
            Direction.STRONG_DOWN -> "market crash, red lava"
            Direction.SIDEWAYS -> "perfect stability, zen digital garden"
        }

    val verdict =
        when (sentiment) {
            Direction.STRONG_UP, Direction.UP -> "BULLISH BREAKOUT"
            Direction.STRONG_DOWN, Direction.DOWN -> "BEARISH DROP"
            Direction.SIDEWAYS -> "SIDEWAYS STABLE"
        }

    return "COMMAND: Create a 5-second STATIC video with NO camera movement and NO text animation. " +
        "SCENE: A central, ultra-sharp high-contrast terminal screen. " +
        "ATMOSPHERE: Still environment with $mood. Only subtle background particles. " +
        "TEXT INSTRUCTION: The screen MUST remain perfectly still. Display the following text EXACTLY as written: " +
        "\"SYMBOL: $asset\" " +
        "\"VERDICT: $verdict\" " +
        "\"CURRENT: ${String.format(java.util.Locale.US, "$%.2f", prediction.currentPrice)}\" " +
        "\"LOW: ${String.format(java.util.Locale.US, "$%.2f", low)}\" " +
        "\"HIGH: ${String.format(java.util.Locale.US, "$%.2f", high)}\" " +
        "\"DATE: $dateStr\". " +
        "VISUALS: Place $symbolDesc at the top. Use professional, sharp, bold neon fonts. " +
        "All text must be in English and perfectly readable. Do not animate the letters."
}

fun generateVisualImagePrompt(prediction: PricePrediction): String {
    val sentiment =
        prediction.ensembleConsensus.direction.name
            .lowercase()
    val mood = if (sentiment.contains("up")) "cyberpunk neon green bull market city" else "dark neon red rainy back alley market"
    return "cinematic close up, futuristic terminal screen showing $sentiment data for ${prediction.coinId}, $mood, blade runner aesthetic, high detail, 8k"
}
