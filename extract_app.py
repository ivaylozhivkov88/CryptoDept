def should_skip_dir(dir_name: str) -> bool:
    return dir_name in SKIP_DIRS


def should_skip_path(path: str) -> bool:
    for pattern in SKIP_PATH_PATTERNS:
        if re.search(pattern, path):
            return True
    return False


def should_skip_file(file_path: str, mode: str = "smart") -> bool:
    """Determine if file should be skipped based on mode."""
    name = os.path.basename(file_path)
    
    # Always skip these
    if name in SKIP_FILE_NAMES:
        return True
    
    for prefix in SKIP_FILE_PREFIXES:
        if name.startswith(prefix):
            return True
    
    for pattern in SKIP_FILE_PATTERNS:
        if re.match(pattern, name):
            return True
    
    ext = os.path.splitext(name)[1].lower()
    
    # In code mode → only kotlin/java
    if mode == "code":
        return ext not in CODE_EXTENSIONS
    
    # In smart mode → code + selected configs + AndroidManifest
    if mode == "smart":
        # Include all .kt/.java
        if ext in CODE_EXTENSIONS:
            return False
        # Include build config files
        if ext in CONFIG_EXTENSIONS:
            return False
        # Include only IMPORTANT xml files
        if ext == ".xml":
            # Manifest is critical
            if name == "AndroidManifest.xml":
                return False
            # strings.xml gets included (translations)
            if name == "strings.xml":
                return False
            # Skip themes, colors, layout, drawables, animations
            return True
        # Include only root-level .md files
        if ext in DOC_EXTENSIONS:
            # Get parent dir
            parent = os.path.dirname(file_path)
            # Allow if in root or docs/ folder
            if parent == ROOT_DIR or os.path.basename(parent) == "docs":
                return False
            return True
        return True
    
    # In full mode → almost everything
    if mode == "full":
        # Skip binary types
        skip_bin = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".ico",
                    ".ttf", ".otf", ".woff", ".woff2",
                    ".mp3", ".mp4", ".wav", ".ogg",
                    ".jar", ".aar", ".zip", ".apk", ".aab",
                    ".so", ".dll", ".dylib",
                    ".class", ".dex"}
        return ext in skip_bin
    
    # Skeleton mode → almost everything skipped
    if mode == "skeleton":
        return name not in SKELETON_INCLUDE_FILES
    
    return False


