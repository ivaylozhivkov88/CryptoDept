KOTLIN_BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)
KOTLIN_LINE_COMMENT = re.compile(r"//[^\n]*")
KDOC_BLOCK = re.compile(r"/\*\*.*?\*/", re.DOTALL)
MULTI_BLANK = re.compile(r"\n\s*\n\s*\n+")


def strip_kotlin_comments(content: str) -> str:
    """Remove block + line comments to save tokens. Keeps annotations."""
    # Запазваме KDoc (/** ... */) защото съдържат semantic info
    # но премахваме обикновени блокови коментари /* ... */ и // line
    
    lines = content.split("\n")
    output_lines = []
    in_block_comment = False
    
    for line in lines:
        # Skip целия line ако е само comment
        stripped = line.strip()
        
        # Skip празни comments като "// "
        if stripped.startswith("// ") and len(stripped) <= 3:
            continue
        if stripped == "//":
            continue
            
        # Detect start/end of block comment
        if "/*" in line and "*/" not in line:
            in_block_comment = True
            continue
        if in_block_comment:
            if "*/" in line:
                in_block_comment = False
            continue
            
        # Remove inline // comments (but keep URLs like https://)
        # Simple heuristic: if "//" не е в start of line и предходният char не е ":"
        if "//" in line:
            idx = line.find("//")
            # Check if preceded by ":" (URL)
            if idx > 0 and line[idx - 1] == ":":
                pass  # keep
            else:
                line = line[:idx].rstrip()
                if not line.strip():
                    continue
                    
        output_lines.append(line)
    
    result = "\n".join(output_lines)
    
    # Collapse multiple blank lines
    result = MULTI_BLANK.sub("\n\n", result)
    
    return result


def compact_whitespace(content: str) -> str:
    """Reduce excessive whitespace."""
    return MULTI_BLANK.sub("\n\n", content)


def process_content(content: str, file_path: str) -> str:
    """Apply token-saving transformations based on file type."""
    if not STRIP_COMMENTS_FROM_KOTLIN:
        return content
    
    if file_path.endswith((".kt", ".kts", ".java")):
        return strip_kotlin_comments(content)
    
    # For all other files: just compact whitespace
    return compact_whitespace(content)


