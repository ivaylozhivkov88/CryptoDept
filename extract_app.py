def classify_layer(rel_path: str) -> str:
    """Classify file by architecture layer (for stats only)."""
    p = rel_path.replace("\\", "/").lower()

    if "/build/" in p or "/.gradle/" in p:
        return None  # skip

    # Build / config
    if rel_path.endswith((".gradle", ".gradle.kts", ".pro", ".properties", ".toml")):
        return "build"

    # Tests
    if "/test/" in p:
        return "tests-unit"
    if "/androidtest/" in p:
        return "tests-android"

    # Architecture layers (Kotlin specific)
    if "/data/api/" in p:
        return "data-api"
    if "/data/db/" in p or "/data/dao/" in p or "/data/entity/" in p:
        return "data-db"
    if "/data/repository/" in p or "repositoryimpl" in p:
        return "data-repo"
    if "/data/" in p:
        return "data-other"
    if "/domain/model/" in p:
        return "domain-models"
    if "/domain/repository/" in p:
        return "domain-repo-interface"
    if "/domain/usecase/" in p:
        return "domain-usecase"
    if "/domain/" in p:
        return "domain-other"
    if "/di/" in p:
        return "di"
    if "/ui/" in p:
        return "ui"
    if "/viewmodel/" in p:
        return "viewmodel"
    if "/service/" in p:
        return "service"
    if "/widget/" in p:
        return "widget"
    if "/util/" in p or "/utility/" in p:
        return "util"

    # Resources
    if "/res/values/strings.xml" in p:
        return "strings"
    if "/res/" in p:
        return "resources"

    # Docs
    if rel_path.endswith(".md") or rel_path.endswith(".txt"):
        return "docs"

    return "other"


