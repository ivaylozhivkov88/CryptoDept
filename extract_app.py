# ==========================================================

def scan_for_secrets(content: str, rel_path: str) -> list:
    """Return list of (description, snippet) for suspicious patterns."""
    findings = []
    
    # Skip Matrix Rain (animation alphabet — false positive)
    if "MatrixRainScreen" in rel_path:
        return findings
    
    for pattern, description in SECRET_PATTERNS:
        matches = re.findall(pattern, content)
        for match in matches:
            # Truncate for safety
            snippet = match[:20] + "..." if len(match) > 20 else match
            findings.append((description, snippet))
    
    return findings


