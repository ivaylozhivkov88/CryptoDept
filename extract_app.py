# ==========================================================

def collect_files(mode: str) -> tuple:
    """
    Walk filesystem and collect files matching criteria.
    Returns (files_data, stats, secrets).
    """
    files_data = []  # list of (rel_path, content, size_bytes)
    stats = defaultdict(lambda: {"count": 0, "bytes": 0})
    secrets = []
    
    root = Path(ROOT_DIR)
    if not root.exists():
        print(f"ERROR: {ROOT_DIR} does not exist!")
        sys.exit(1)
    
    for current_path, dirs, files in os.walk(ROOT_DIR):
        # Filter directories in place
        dirs[:] = [d for d in dirs if not should_skip_dir(d)]
        
        # Skip path if matches skip patterns
        if should_skip_path(current_path):
            continue
        
        for filename in files:
            full_path = os.path.join(current_path, filename)
            rel_path = os.path.relpath(full_path, ROOT_DIR)
            
            # Apply file-level filtering
            if should_skip_file(full_path, mode):
                continue
            
            # Check file size
            try:
                file_size = os.path.getsize(full_path)
                if file_size > MAX_FILE_SIZE_BYTES:
                    continue
                if file_size == 0:
                    continue  # skip empty files
            except OSError:
                continue
            
            # Read content
            try:
                with open(full_path, "r", encoding="utf-8") as f:
                    content = f.read()
            except (UnicodeDecodeError, OSError):
                # Try latin-1 as fallback
                try:
                    with open(full_path, "r", encoding="latin-1") as f:
                        content = f.read()
                except OSError:
                    continue
            
            # Apply token-saving transformations
            processed = process_content(content, full_path)
            
            # Scan for secrets
            file_secrets = scan_for_secrets(content, rel_path)
            for desc, snippet in file_secrets:
                secrets.append((rel_path, desc, snippet))
            
            # Classify layer
            layer = classify_layer(rel_path)
            if layer:
                stats[layer]["count"] += 1
                stats[layer]["bytes"] += len(processed.encode("utf-8"))
            
            files_data.append((rel_path, processed, len(processed.encode("utf-8"))))
    
    return files_data, stats, secrets


# ==========================================================
# OUTPUT WRITER (token-optimized format)
# ==========================================================

def write_output(mode: str, files_data: list, stats: dict, secrets: list):
    """Write compact, token-optimized output."""
    
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    out_path = os.path.join(OUTPUT_DIR, f"{PROJECT_NAME}_DUMP.txt")
    
    # Sort files: critical first, then by layer, then alphabetically
    def sort_key(item):
        rel_path, _, _ = item
        name = os.path.basename(rel_path)
        # Critical files first
        if name in CRITICAL_FILES:
            return (0, rel_path)
        return (1, rel_path)
    
    files_data.sort(key=sort_key)
    
    total_files = len(files_data)
    total_bytes = sum(size for _, _, size in files_data)
    
    with open(out_path, "w", encoding="utf-8") as f:
        # ============ HEADER ============
        f.write(f"# {PROJECT_NAME} DUMP — {mode.upper()} MODE\n")
        f.write(f"# Generated: {timestamp}\n")
        f.write(f"# Root: {ROOT_DIR}\n")
        f.write(f"# Files: {total_files}\n")
        f.write(f"# Size: {total_bytes / 1024:.1f} KB\n")
        f.write("\n")
        
        # ============ LAYER STATS ============
        f.write("## LAYERS\n")
        for layer_name in sorted(stats.keys()):
            data = stats[layer_name]
            f.write(f"  {layer_name:20s} {data['count']:4d} files  {data['bytes'] / 1024:.1f} KB\n")
        f.write("\n")
        
        # ============ SECRETS ============
        if secrets:
            f.write("## SECRETS DETECTED\n")
            for rel_path, desc, snippet in secrets:
                f.write(f"  {rel_path}  →  {desc}: {snippet}\n")
            f.write("\n")
        
        # ============ FILES ============
        f.write("## FILES\n\n")
        
        for rel_path, content, size in files_data:
            # Compact file header: just path + size
            normalized_path = rel_path.replace("\\", "/")
            f.write(f"### {normalized_path}\n")
            f.write("```\n")
            f.write(content)
            if not content.endswith("\n"):
                f.write("\n")
            f.write("```\n\n")
    
    return out_path, total_files, total_bytes


